#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn locales_have_the_same_keys() {
        for (key, _) in ZH {
            assert!(
                EN.iter().any(|(candidate, _)| candidate == key),
                "missing en-US key: {key}"
            );
        }
        for (key, _) in EN {
            assert!(
                ZH.iter().any(|(candidate, _)| candidate == key),
                "missing zh-CN key: {key}"
            );
        }
    }

    #[test]
    fn every_key_resolves_in_both_locales_without_the_fallback() {
        for (key, _) in ZH {
            assert!(!tr(Language::ZhCn, key).is_empty(), "{key}");
            assert!(!tr(Language::EnUs, key).is_empty(), "{key}");
        }
        for (key, _) in EN {
            assert!(!tr(Language::ZhCn, key).is_empty(), "{key}");
            assert!(!tr(Language::EnUs, key).is_empty(), "{key}");
        }
    }

    #[test]
    fn format_placeholders_match_across_locales() {
        for (key, zh) in ZH {
            let Some((_, en)) = EN.iter().find(|(candidate, _)| candidate == key) else {
                continue;
            };
            let placeholders = |text: &str| {
                let mut found: Vec<String> = Vec::new();
                let mut rest = text;
                while let Some(start) = rest.find('{') {
                    let after = &rest[start + 1..];
                    let Some(end) = after.find('}') else {
                        break;
                    };
                    found.push(after[..end].to_string());
                    rest = &after[end + 1..];
                }
                found.sort_unstable();
                found
            };
            assert_eq!(
                placeholders(zh),
                placeholders(en),
                "placeholder mismatch for {key}"
            );
        }
    }
}
